def file_too_large(limit_bytes: int) -> str:
    return f"حجم فایل از سقف {format_size(limit_bytes)} بیشتر است."


def format_size(size: int) -> str:
    if size < 1024:
        return f"{size} بایت"
    if size < 1024 * 1024:
        amount = size / 1024
        return f"{amount:.1f} کیلوبایت"
    amount = size / (1024 * 1024)
    return f"{amount:.1f} مگابایت"
